//! Character-class lookup table — Rust translation of `lib/ctype.c`.
//!
//! Pure data (`EXPORT_SYMBOL(_ctype)`), no functions — the 256-entry
//! table `<linux/ctype.h>`'s `isalpha`/`isdigit`/`isspace`/etc. macros
//! index via `__ismask(c)`. Values computed directly from the C
//! initializer's `_U|_L|_D|_C|_P|_S|_X|_SP` bit combinations
//! (`_U`=0x01 upper, `_L`=0x02 lower, `_D`=0x04 digit, `_C`=0x08 cntrl,
//! `_P`=0x10 punct, `_S`=0x20 space, `_X`=0x40 hex, `_SP`=0x80 hard
//! space), byte-for-byte identical to the original table.
//!
//! `#[export]` (rust/macros/export.rs) only accepts `ItemFn` — it can't
//! bindgen-typecheck a `static`, same gap noted in `lib/hexdump_rs.rs`.
//! This is `#[no_mangle]` directly; in this non-modular kernel that's
//! sufficient for `EXPORT_SYMBOL`'s only real effect (a resolvable
//! `System.map` symbol).

